var _homeData = null;
var _detailCache = {};
function adapterHome() {
    if (_homeData) return _homeData;
    var result = {};
    if (ADAPTER === 'app3q') result = app3qCall('home', {});
    else if (ADAPTER === 'niulai') result = niulaiCall('home', { filter: true, sdk: SDK_INT });
    else if (ADAPTER === 'fuyun') {
        result.classes = [];
        for (var i = 0; i < FY_CHANNELS.length; i++) result.classes.push({ id: FY_CHANNELS[i], name: FY_CHANNELS[i] });
        result.list = fuyunCategory(ANIME_ONLY ? '动漫' : '剧集', 1, { sort: '最新' });
    } else if (ADAPTER === 'jianpian') {
        var categoriesRoot = jpGet('/api/v2/settings/homeCategory');
        result.classes = categoriesRoot.data instanceof Array ? categoriesRoot.data : [];
        result.list = jpList('/api/slide/list?pos_id=88', ANIME_ONLY ? '动漫' : '影视');
    }
    _homeData = result && typeof result === 'object' ? result : {};
    return _homeData;
}
function classList() {
    var values = adapterHome().classes;
    values = values instanceof Array ? values : [];
    var out = [];
    for (var i = 0; i < values.length; i++) {
        var value = values[i] || {};
        var id = value.id != null ? value.id : value.type_id;
        var name = value.name || value.type_name || value.title || '';
        if (id == null || !name) continue;
        if (ANIME_ONLY && !animeText(name) && !animeText(id)) continue;
        out.push({ id: text(id), name: clean(name) });
    }
    if (ANIME_ONLY && !out.length) {
        if (ADAPTER === 'jianpian') out.push({ id: '3', name: '动漫' });
        else if (ADAPTER === 'fuyun') out.push({ id: '动漫', name: '动漫' }, { id: '少儿', name: '少儿' });
        else out.push({ id: 'comic', name: '动漫' });
    }
    return out;
}
function adapterCategory(category, page, filters) {
    category = text(category);
    page = Math.max(1, Number(page) || 1);
    filters = filters || {};
    if (ADAPTER === 'app3q') return mapCards((app3qCall('category', { tid: category, page: page }).list || []), category);
    if (ADAPTER === 'niulai') {
        return mapCards((niulaiCall('category', { tid: category, page: page, extend: filters, sdk: SDK_INT }).list || []), category);
    }
    if (ADAPTER === 'fuyun') return fuyunCategory(category, page, filters);
    if (ADAPTER === 'jianpian') {
        if (category === '50' || category === '99' || category === '111') {
            return jpList('/api/dyTag/list?category_id=' + encode(category) + '&page=' + page, category);
        }
        var path = '/api/crumb/list?fcate_pid=' + encode(category) + '&area=' + encode(filters.area || '') +
            '&year=' + encode(filters.year || '') + '&type=0&sort=' + encode(filters.sort || 'updata') +
            '&page=' + page + '&category_id=' + encode(category);
        return jpList(path, category === '3' ? '动漫' : '影视');
    }
    return [];
}
function adapterSearch(keyword, page) {
    keyword = trim(keyword);
    page = Math.max(1, Number(page) || 1);
    if (!keyword) {
        var classes = classList();
        return classes.length ? adapterCategory(classes[0].id, page, {}) : mapCards(adapterHome().list || []);
    }
    if (ADAPTER === 'app3q') return mapCards((app3qCall('search', { key: keyword, page: page }).list || []));
    if (ADAPTER === 'niulai') return mapCards((niulaiCall('search', { keyword: keyword, page: page, sdk: SDK_INT }).list || []));
    if (ADAPTER === 'fuyun') {
        return mapCards(fuyunJson(FY_HOST + '/vc/api/search/' + encode(keyword) + '/' + page + '.json') || []);
    }
    if (ADAPTER === 'jianpian') {
        return jpList('/api/v2/search/videoV2?key=' + encode(keyword) + '&category_id=88&page=' + page + '&pageSize=20');
    }
    return [];
}
function adapterDetail(id) {
    var key = text(id);
    if (_detailCache[key]) return _detailCache[key];
    var result = {};
    if (ADAPTER === 'app3q') result = app3qCall('detail', { id: key });
    else if (ADAPTER === 'niulai') result = niulaiCall('detail', { id: key, sdk: SDK_INT });
    else if (ADAPTER === 'fuyun') result = fuyunDetail(key);
    else if (ADAPTER === 'jianpian') result = jianpianDetail(key);
    if (ADAPTER === 'app3q' || ADAPTER === 'niulai') {
        var vod = result.vod || {};
        var out = {
            id: text(vod.id != null ? vod.id : key), name: clean(vod.name), pic: imageUrl(vod.pic || ''),
            desc: clean(vod.content || vod.desc || ''), type: clean(vod.type || ''), year: text(vod.year || ''),
            remarks: clean(vod.remarks || ''), actor: clean(vod.actor || ''), director: clean(vod.director || ''), episodes: []
        };
        var sources = result.sources instanceof Array ? result.sources : [];
        for (var i = 0; i < sources.length; i++) {
            var source = sources[i] || {}, episodes = source.episodes instanceof Array ? source.episodes : [];
            for (var j = 0; j < episodes.length; j++) {
                var ep = episodes[j] || {}, meta;
                if (ADAPTER === 'app3q') meta = { adapter: 'app3q', play_id: ep.play_id };
                else meta = {
                    adapter: 'niulai', flag: text(source.name), url: text(ep.url != null ? ep.url : ep.play_id),
                    line: text(ep.line || source.name),
                    title: text(ep.name), vodname: text(vod.name), sdk: SDK_INT, force_session: false
                };
                out.episodes.push({
                    name: clean(ep.name) || ('第' + (j + 1) + '集'), route: clean(source.name || ('线路' + (i + 1))),
                    url: 'bridge|' + b64Encode(JSON.stringify(meta))
                });
            }
        }
        result = out;
    }
    _detailCache[key] = result;
    return result;
}
function adapterPlay(flag) {
    flag = text(flag);
    if (ADAPTER === 'fuyun') return fuyunPlay(flag);
    if (ADAPTER === 'jianpian') return { url: flag, type: mediaType(flag), headers: jpHeaders() };
    if (flag.indexOf('bridge|') !== 0) return { url: '', type: 'auto' };
    var meta = parse(b64Decode(flag.substring(7))) || {};
    var result = meta.adapter === 'app3q'
        ? app3qCall('play', { play_id: meta.play_id })
        : niulaiCall('player', {
            flag: meta.flag, url: meta.url, line: meta.line, title: meta.title,
            vodname: meta.vodname, sdk: meta.sdk || SDK_INT, force_session: !!meta.force_session
        });
    if (meta.adapter === 'niulai' && !(result && (result.url || result.play_url))) {
        result = niulaiCall('player', {
            flag: meta.flag, url: meta.url, line: meta.line, title: meta.title,
            vodname: meta.vodname, sdk: meta.sdk || SDK_INT, force_session: true
        });
    }
    var direct = text(result.url || result.play_url || '');
    return { url: direct, type: normalizedMediaType(result.type, direct), headers: result.header || result.headers || {} };
}

