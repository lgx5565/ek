function categories() {
    try {
        var out = [{ key: '', title: '推荐' }], classes = classList();
        for (var i = 0; i < classes.length; i++) {
            var item = { key: classes[i].id, title: classes[i].name };
            /* App3Q has no proven filter parameters; do not advertise filters that searchFiltered cannot apply. */
            if (ADAPTER !== 'app3q') item.filters = filterSet();
            out.push(item);
        }
        return JSON.stringify(out);
    } catch (ignore) { return JSON.stringify([{ key: '', title: '推荐' }]); }
}
function homeSections() {
    try {
        var out = [], home = adapterHome(), cards = mapCards(home.list || [], ANIME_ONLY ? '动漫' : '影视');
        if (cards.length) out.push({ title: SOURCE_NAME + (ANIME_ONLY ? '动漫推荐' : '首页推荐'), key: '__hero__', items: cards.slice(0, 12) });
        var classes = classList(), max = ANIME_ONLY ? Math.min(2, classes.length) : Math.min(3, classes.length);
        for (var i = 0; i < max; i++) {
            var list = adapterCategory(classes[i].id, 1, {});
            if (list.length) out.push({ title: SOURCE_NAME + ' · ' + classes[i].name, key: classes[i].id, items: list.slice(0, 12) });
        }
        if (!out.length && cards.length) out.push({ title: SOURCE_NAME, key: '', items: cards });
        return JSON.stringify(out);
    } catch (ignore) { return '[]'; }
}
function search(keyword, page) {
    try {
        var key = trim(keyword), classes = key ? classList() : [];
        for (var i = 0; i < classes.length; i++) {
            if (text(classes[i].id) === key) return JSON.stringify(adapterCategory(key, page, {}));
        }
        return JSON.stringify(adapterSearch(key, page));
    } catch (ignore) { return '[]'; }
}
